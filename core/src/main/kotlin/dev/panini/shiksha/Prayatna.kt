enum class AbhyantaraPrayatna {
    SPRSTA,       // Sparśa (k-m)
    ISAT_SPRSTA,  // Antastha (y, r, l, v)
    ISAT_VIVRTA,  // Ūṣman (ś, ṣ, s, h)
    VIVRTA,       // Vowels
    SAMVRTA       // Short 'a' in actual speech
}

