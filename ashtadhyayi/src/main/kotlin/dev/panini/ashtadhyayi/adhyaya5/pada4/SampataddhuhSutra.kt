/**
 * Sūtra 5.4.139: सम्पाताद्द्हुः.
 * Samāsānta suffix after sampāt.
 */
object SampataddhuhSutra : Sutra<SamasaRuleContext, SamasaRuleResult>(
    number = "5.4.139",
    text = "सम्पाताद्द्हुः",
    hindiExplanation = "सम्पात उत्तरपद से दुर् पूर्वपद परे होने पर समासान्त प्रत्यय होता है।",
    type = SutraType.NITYA,
    chapter = 5,
    pada = 4,
    optional = false,
    kramaValue = 540139,
    role = SutraRole.Niyama,
    action = SutraAction.PRATYAYA_SELECTION,
    scope = SutraScope.DERIVATION,
    samasaType = SamasaType.BAHUVRIHI,
    samasaPriority = 10,
), SamasaSutra {
    override fun matches(context: SamasaRuleContext): Boolean {
        if (context.padas.size < 2) return false
        val first = context.padas.first().upadesha
        val last = context.padas.last().upadesha
        return first == "दुर्" && last == "सम्पात"
    }

    override fun apply(context: SamasaRuleContext): SamasaRuleResult {
        val compoundStem = context.padas.joinToString("") { it.upadesha } + "अ"
        return SamasaRuleResult.Formed(
            compoundStem = compoundStem,
            explanation = "5.4.139 adds Samāsānta after dur + sampāt in '$compoundStem'.",
        )
    }
}
