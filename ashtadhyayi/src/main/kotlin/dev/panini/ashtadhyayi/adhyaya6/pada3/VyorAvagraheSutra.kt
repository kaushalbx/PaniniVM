/**
 * Sūtra 6.3.82: व्योरवग्रहे (registered as 6.3.182).
 * Transformation of vi / o before avagraha.
 */
object VyorAvagraheSutra : Sutra<SamasaRuleContext, SamasaRuleResult>(
    number = "6.3.182",
    text = "व्योरवग्रहे",
    hindiExplanation = "अवग्रह विषय में वि तथा ओ पूर्वपद का रूप परिवर्तन नियम लागू होता है।",
    type = SutraType.NITYA,
    chapter = 6,
    pada = 3,
    optional = false,
    kramaValue = 630182,
    role = SutraRole.Niyama,
    action = SutraAction.ADESHA,
    scope = SutraScope.DERIVATION,
    samasaType = SamasaType.TATPURUSA,
    samasaPriority = 10,
), SamasaSutra {
    override fun matches(context: SamasaRuleContext): Boolean {
        if (context.padas.size < 2) return false
        val first = context.padas.first().upadesha
        return first == "वि" || first == "ओ"
    }

    override fun apply(context: SamasaRuleContext): SamasaRuleResult {
        val compoundStem = context.padas.joinToString("") { it.upadesha }
        return SamasaRuleResult.Formed(
            compoundStem = compoundStem,
            explanation = "6.3.82 applies vi/o avagraha transformation in '$compoundStem'.",
        )
    }
}
