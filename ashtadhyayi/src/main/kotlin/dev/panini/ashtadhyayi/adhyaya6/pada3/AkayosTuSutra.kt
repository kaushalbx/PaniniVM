/**
 * Sūtra 6.3.61: अकयोस्तु.
 * Pūrvapada rule before aka.
 */
object AkayosTuSutra : Sutra<SamasaRuleContext, SamasaRuleResult>(
    number = "6.3.61",
    text = "अकयोस्तु",
    hindiExplanation = "अक (अकच्) प्रत्ययान्त उत्तरपद परे होने पर पूर्वपद नियम लागू होता है।",
    type = SutraType.NITYA,
    chapter = 6,
    pada = 3,
    optional = false,
    kramaValue = 630061,
    role = SutraRole.Niyama,
    action = SutraAction.NIYAMA,
    scope = SutraScope.DERIVATION,
    samasaType = SamasaType.TATPURUSA,
    samasaPriority = 10,
), SamasaSutra {
    override fun matches(context: SamasaRuleContext): Boolean {
        if (context.padas.size < 2) return false
        val last = context.padas.last().upadesha
        return last.endsWith("क") || last.endsWith("अक")
    }

    override fun apply(context: SamasaRuleContext): SamasaRuleResult {
        val compoundStem = context.padas.joinToString("") { it.upadesha }
        return SamasaRuleResult.Formed(
            compoundStem = compoundStem,
            explanation = "6.3.61 applies pūrvapada rule before aka in '$compoundStem'.",
        )
    }
}
