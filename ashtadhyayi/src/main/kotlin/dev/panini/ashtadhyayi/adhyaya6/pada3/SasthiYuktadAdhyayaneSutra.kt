/**
 * Sūtra 6.3.74: षष्ठीयुक्तादध्ययने.
 * Genitive condition in study/recitation context.
 */
object SasthiYuktadAdhyayaneSutra : Sutra<SamasaRuleContext, SamasaRuleResult>(
    number = "6.3.74",
    text = "षष्ठीयुक्तादध्ययने",
    hindiExplanation = "अध्ययन अर्थ में षष्ठीयुक्त पद से परे पूर्वपद नियम लागू होता है।",
    type = SutraType.NITYA,
    chapter = 6,
    pada = 3,
    optional = false,
    kramaValue = 630074,
    role = SutraRole.Niyama,
    action = SutraAction.NIYAMA,
    scope = SutraScope.DERIVATION,
    samasaType = SamasaType.TATPURUSA,
    samasaPriority = 10,
), SamasaSutra {
    override fun matches(context: SamasaRuleContext): Boolean {
        if (context.padas.size < 2) return false
        val last = context.padas.last().upadesha
        return last == "अध्ययन" || last == "पाठ"
    }

    override fun apply(context: SamasaRuleContext): SamasaRuleResult {
        val compoundStem = context.padas.joinToString("") { it.upadesha }
        return SamasaRuleResult.Formed(
            compoundStem = compoundStem,
            explanation = "6.3.74 applies genitive study pūrvapada rule in '$compoundStem'.",
        )
    }
}
