/**
 * Sūtra 6.3.43: गरुध्यै चात्मनः.
 * Pūrvapada rule for ātman.
 */
object GarudhyaiChatmanahSutra : Sutra<SamasaRuleContext, SamasaRuleResult>(
    number = "6.3.43",
    text = "गरुध्यै चात्मनः",
    hindiExplanation = "गरुध्यै उत्तरपद परे होने पर आत्मन् पूर्वपद नियम लागू होता है।",
    type = SutraType.NITYA,
    chapter = 6,
    pada = 3,
    optional = false,
    kramaValue = 630043,
    role = SutraRole.Niyama,
    action = SutraAction.NIYAMA,
    scope = SutraScope.DERIVATION,
    samasaType = SamasaType.TATPURUSA,
    samasaPriority = 10,
), SamasaSutra {
    override fun matches(context: SamasaRuleContext): Boolean {
        if (context.padas.size < 2) return false
        val first = context.padas.first().upadesha
        return first == "आत्मन्" || first == "आत्मा"
    }

    override fun apply(context: SamasaRuleContext): SamasaRuleResult {
        val compoundStem = context.padas.joinToString("") { it.upadesha }
        return SamasaRuleResult.Formed(
            compoundStem = compoundStem,
            explanation = "6.3.43 applies ātman pūrvapada rule in '$compoundStem'.",
        )
    }
}
