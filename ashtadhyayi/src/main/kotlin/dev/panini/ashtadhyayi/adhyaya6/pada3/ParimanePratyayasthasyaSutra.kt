/**
 * Sūtra 6.3.18: परिमाणे प्रत्ययस्थस्य.
 * Pūrvapada rules for measure suffixes.
 */
object ParimanePratyayasthasyaSutra : Sutra<SamasaRuleContext, SamasaRuleResult>(
    number = "6.3.18",
    text = "परिमाणे प्रत्ययस्थस्य",
    hindiExplanation = "परिमाणवाचक प्रत्ययस्थ पद में पूर्वपद स्वर/दीर्घ नियम लागू होता है।",
    type = SutraType.NITYA,
    chapter = 6,
    pada = 3,
    optional = false,
    kramaValue = 630018,
    role = SutraRole.Niyama,
    action = SutraAction.NIYAMA,
    scope = SutraScope.DERIVATION,
    samasaType = SamasaType.TATPURUSA,
    samasaPriority = 10,
), SamasaSutra {
    override fun matches(context: SamasaRuleContext): Boolean {
        if (context.padas.size < 2) return false
        return context.samasaType == SamasaType.TATPURUSA
    }

    override fun apply(context: SamasaRuleContext): SamasaRuleResult {
        val compoundStem = context.padas.joinToString("") { it.upadesha }
        return SamasaRuleResult.Formed(
            compoundStem = compoundStem,
            explanation = "6.3.18 applies measure suffix rule for '$compoundStem'.",
        )
    }
}
