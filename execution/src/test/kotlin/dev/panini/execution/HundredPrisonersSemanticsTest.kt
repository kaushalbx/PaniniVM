package dev.panini.execution

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

class HundredPrisonersSemanticsTest {
    @Test
    fun `box inspection retrieves by grammatical source and location roles`() {
        val results = PaniniVM().evalScript(
            """
            पेटिकादर्शन + सुँ इति प्रक्रिया + सुँ असँ + लट् + तिप् ।
            पेटिकाक्रम + ङसिँ पेटिकाक्रमाङ्क + ङि मूल्य + अम् ग्रहँ + श्ना + लोट् + सिप् ।
            फल + अम् पेटिकाक्रमाङ्क + ङि स्था + णिच् + लोट् + सिप् ।
            यदि पेटिकाक्रमाङ्क + सुँ बन्दिसङ्ख्या + टा सम + सुँ असँ + लट् + तिप्
                तर्हि सत्य + अम् स्वसङ्ख्याप्राप्ति + ङि स्था + णिच् + लोट् + सिप्
                अन्यथा असत्य + अम् स्वसङ्ख्याप्राप्ति + ङि स्था + णिच् + लोट् + सिप् ॥
            द्वि + अम् एक + अम् च सम् + ग्रहँ + श्ना + लोट् + सिप्
                ततः फल + अम् पेटिकाक्रम + ङि स्था + णिच् + लोट् + सिप् ।
            एक + अम् पेटिकाक्रमाङ्क + ङि स्था + णिच् + लोट् + सिप् ।
            एक + अम् बन्दिसङ्ख्या + ङि स्था + णिच् + लोट् + सिप् ।
            पेटिकादर्शन + टा डुकृञ् + उ + लोट् + सिप् ।
            """.trimIndent(),
        )

        assertTrue(results.none { it is ExecutionResult.Failure || it is ExecutionResult.NeedsInput }, results.toString())
        assertEquals(
            SanskritValue.Satya(false),
            results.filterIsInstance<ExecutionResult.Success>().last().typedValue,
        )
    }

