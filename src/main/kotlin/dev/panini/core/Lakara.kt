package dev.panini.core

/** The ten lakāras, retaining their grammatical upadeśa forms. */
enum class Lakara(val upadesha: String) {
    LAT("लट्"),
    LIT("लिट्"),
    LUT("लुट्"),
    LRT("लृट्"),
    LET("लेट्"),
    LOT("लोट्"),
    LANG("लङ्"),
    LING("लिङ्"),
    LUNG("लुङ्"),
    LRNG("लृङ्"),
}
